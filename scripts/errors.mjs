// The error catalogue: each mistake the type tests hold to not compiling, what TypeScript says of it, and why, by
// topic, in docs/errors.md. The cases are the type tests themselves: each `@ts-expect-error` line says in plain words
// what is wrong with the line under it. This compiles them with those directives blanked out, through TypeScript's
// API so no file moves and no line shifts, and puts each error beside the words of the directive above it.
//
//   npm run errors:check    fails when docs/errors.md is not what the compiler says
//   npm run errors:update   writes it
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { basename, join, resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const ts = createRequire(join(root, 'package.json'))('typescript')
const out = join(root, 'docs', 'errors.md')
const folder = join(root, 'type-tests')
const files = readdirSync(folder).filter((name) => name.endsWith('.ts')).sort().map((name) => join(folder, name))
const DIRECTIVE = /^(\s*)\/\/ @ts-expect-error (.*)$/

const config = ts.getParsedCommandLineOfConfigFile(join(root, 'tsconfig.json'), {}, { ...ts.sys, onUnRecoverableConfigFileDiagnostic: () => {} })
const host = ts.createCompilerHost(config.options)
const read = host.getSourceFile.bind(host)
// A type test's directives become empty comments of the same line, so each error lands on the line it was held to.
host.getSourceFile = (name, version, onError, fresh) => {
  if (!files.includes(resolve(name))) return read(name, version, onError, fresh)
  const text = readFileSync(name, 'utf8').replaceAll('\r\n', '\n').split('\n').map((line) => (DIRECTIVE.test(line) ? line.replace(DIRECTIVE, '$1//') : line)).join('\n')
  return ts.createSourceFile(name, text, version)
}
const program = ts.createProgram(files, config.options, host)
const diagnostics = ts.getPreEmitDiagnostics(program)

/** What TypeScript says, on one line: its code, and the first line of its message, cut where it runs long. */
const said = (diagnostic) => {
  const first = ts.flattenDiagnosticMessageText(diagnostic.messageText, '\n').split('\n')[0]
  return `TS${diagnostic.code}: ${first.length > 180 ? `${first.slice(0, 177)}…` : first}`
}
const cell = (text) => text.replaceAll('|', '\\|')

/**
 * Errors that say a name is not there: a case met by one of these fails for a missing import or a typo, not for the
 * mistake its directive names, and holds nothing.
 */
const MISSING = new Set([2304, 2305, 2307, 2552, 2724])
const sections = []
let unexplained = 0
const vacuous = []
for (const file of files) {
  // As written, whatever line endings a checkout gave it.
  const lines = readFileSync(file, 'utf8').replaceAll('\r\n', '\n').split('\n')
  const topic = (lines[0] ?? '').replace(/^\/\/\s*/, '')
  const rows = []
  lines.forEach((line, at) => {
    const directive = DIRECTIVE.exec(line)
    if (!directive) return
    const why = directive[2].trim()
    const own = diagnostics.filter((d) => d.file && resolve(d.file.fileName) === file && d.file.getLineAndCharacterOfPosition(d.start).line === at + 1)
    const wrote = (lines[at + 1] ?? '').trim()
    if (!own.length) unexplained++
    else if (MISSING.has(own[0].code)) vacuous.push(`type-tests/${basename(file)}:${at + 2}: ${said(own[0])}`)
    rows.push(`| \`${cell(wrote.length > 90 ? `${wrote.slice(0, 87)}…` : wrote)}\` | ${own.length ? cell(said(own[0])) : '**nothing: this line compiles**'} | ${cell(why)} |`)
  })
  if (rows.length) sections.push(`## ${topic}\n\n\`type-tests/${basename(file)}\`\n\n| What was written | What TypeScript says | Why |\n|---|---|---|\n${rows.join('\n')}\n`)
}
const text = `# What a compile error means

Each row is a mistake the type tests hold to not compiling (\`type-tests/\`), what TypeScript says of it, and why: the
words of the \`@ts-expect-error\` above it, which say what is wrong and what to write instead. Generated by
\`npm run errors:update\` from TypeScript ${ts.version}; \`npm run errors:check\` holds it to what the compiler says, so a
change in wording shows here. A template's mistakes, which \`vue-tsc\` reports in a component, are the same as these:
\`type-tests/vue-templates/Board.vue\`.

${sections.join('\n')}`
if (vacuous.length) {
  console.error(`These cases fail for a name that is not there, not for the mistake they name, and hold nothing:\n  ${vacuous.join('\n  ')}`)
  process.exit(1)
}
if (unexplained) {
  console.error(`${unexplained} type tests compile without their directive, so they say nothing here: npm run typecheck names them`)
  process.exit(1)
}
if (process.argv.includes('--write')) { writeFileSync(out, text); console.log('docs/errors.md written') }
else if (readFileSync(out, 'utf8').replaceAll('\r\n', '\n') !== text) { console.error('docs/errors.md is not what the compiler says: run npm run errors:update and commit it'); process.exit(1) }
else console.log(`docs/errors.md as the compiler says, ${sections.length} topics`)
